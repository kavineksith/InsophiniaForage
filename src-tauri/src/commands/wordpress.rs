//! One-click WordPress installer. Downloads, extracts, creates a DB,
//! and writes `wp-config.php` with safe random keys.

use crate::core::paths;
use crate::core::AppState;
use crate::error::{ForageError, ForageResult};
use serde::Serialize;
use tauri::State;

#[derive(Debug, Clone, Serialize)]
pub struct WordPressInstallResult {
    pub project_name: String,
    pub url: String,
    pub admin_url: String,
    pub database_name: String,
    pub database_user: String,
}

#[tauri::command]
pub async fn install_wordpress(
    state: State<'_, AppState>,
    project_name: String,
    site_title: Option<String>,
    admin_user: Option<String>,
    admin_password: Option<String>,
    admin_email: Option<String>,
) -> Result<WordPressInstallResult, String> {
    paths::validate_name(&project_name).map_err(|e| e.to_string())?;
    let settings = state.settings.get();

    // 1. Download WordPress.
    let spec = crate::binaries::download::spec_for("wordpress", "latest")
        .map_err(|e| e.to_string())?;
    let wp_dir = crate::binaries::download::download_and_extract(&spec, |_, _| {}).await
        .map_err(|e| e.to_string())?;

    // 2. Copy into the project folder.
    let project_root = paths::project_root(&project_name).map_err(|e| e.to_string())?;
    if project_root.exists() {
        return Err(format!("project '{}' already exists", project_name));
    }
    std::fs::create_dir_all(&project_root).map_err(|e| e.to_string())?;
    copy_dir_recursive(&wp_dir, &project_root).map_err(|e| e.to_string())?;

    // 3. Create database.
    let db_name = format!("wp_{}", project_name.replace('-', "_"));
    let db_user = settings.mariadb.app_user.clone();
    let db_pass = settings.mariadb.app_password.clone();
    let db_host = format!("127.0.0.1:{}", settings.ports.mariadb);

    // Wait for MariaDB to be running, then create DB.
    let client = find_mariadb_client().map_err(|e| e.to_string())?;
    let socket = paths::run_dir().join("mariadb.sock");
    let sql = format!("CREATE DATABASE IF NOT EXISTS `{}`;", db_name);
    run_sql(&client, &socket, &db_user, &db_pass, &sql).map_err(|e| e.to_string())?;

    // 4. Write wp-config.php with random keys.
    let keys = generate_wp_keys();
    let config = render_wp_config(&db_name, &db_user, &db_pass, &db_host, &keys);
    std::fs::write(project_root.join("wp-config.php"), config)
        .map_err(|e| e.to_string())?;

    // 5. Optionally run the WP-CLI install (skip for now — requires wp-cli).
    // The user completes setup via the web wizard at /wp-admin/install.php.

    let url = settings.project_url(&project_name);
    let admin_url = format!("{}/wp-admin/install.php", url);

    Ok(WordPressInstallResult {
        project_name,
        url,
        admin_url,
        database_name: db_name,
        database_user: db_user,
    })
}

fn render_wp_config(db: &str, user: &str, pass: &str, host: &str, keys: &WpKeys) -> String {
    format!(
        r#"<?php
/**
 * Generated by InsophiniaForage. Do not edit by hand — regenerate via the
 * WordPress tab. WordPress configuration file.
 */

// ** Database settings ** //
define('DB_NAME',     '{db}');
define('DB_USER',     '{user}');
define('DB_PASSWORD', '{pass}');
define('DB_HOST',     '{host}');
define('DB_CHARSET',  'utf8mb4');
define('DB_COLLATE',  'utf8mb4_unicode_ci');

// ** Authentication unique keys and salts ** //
define('AUTH_KEY',         '{auth_key}');
define('SECURE_AUTH_KEY',  '{secure_auth_key}');
define('LOGGED_IN_KEY',    '{logged_in_key}');
define('NONCE_KEY',        '{nonce_key}');
define('AUTH_SALT',        '{auth_salt}');
define('SECURE_AUTH_SALT', '{secure_auth_salt}');
define('LOGGED_IN_SALT',   '{logged_in_salt}');
define('NONCE_SALT',       '{nonce_salt}');

// ** Database table prefix ** //
$table_prefix = 'wp_';

// ** Debug mode for development ** //
define('WP_DEBUG', true);
define('WP_DEBUG_LOG', true);
define('WP_DEBUG_DISPLAY', false);

// ** Absolute path to the WordPress directory. ** //
if (!defined('ABSPATH')) {{
    define('ABSPATH', __DIR__ . '/');
}}

require_once ABSPATH . 'wp-settings.php';
"#,
        db = db,
        user = user,
        pass = pass,
        host = host,
        auth_key = keys.auth_key,
        secure_auth_key = keys.secure_auth_key,
        logged_in_key = keys.logged_in_key,
        nonce_key = keys.nonce_key,
        auth_salt = keys.auth_salt,
        secure_auth_salt = keys.secure_auth_salt,
        logged_in_salt = keys.logged_in_salt,
        nonce_salt = keys.nonce_salt,
    )
}

struct WpKeys {
    auth_key: String,
    secure_auth_key: String,
    logged_in_key: String,
    nonce_key: String,
    auth_salt: String,
    secure_auth_salt: String,
    logged_in_salt: String,
    nonce_salt: String,
}

fn generate_wp_keys() -> WpKeys {
    WpKeys {
        auth_key: random_string(64),
        secure_auth_key: random_string(64),
        logged_in_key: random_string(64),
        nonce_key: random_string(64),
        auth_salt: random_string(64),
        secure_auth_salt: random_string(64),
        logged_in_salt: random_string(64),
        nonce_salt: random_string(64),
    }
}

fn random_string(len: usize) -> String {
    // Same xorshift RNG as settings.rs. Sufficient for non-secret dev keys.
    use std::time::{SystemTime, UNIX_EPOCH};
    let charset = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!@#$%^&*()-_ []{}<>~+=,.;:/?|";
    let mut buf = String::with_capacity(len);
    let mut seed = SystemTime::now().duration_since(UNIX_EPOCH).unwrap().as_nanos() as u64
        ^ (std::process::id() as u64).wrapping_mul(0x9E3779B97F4A7C15);
    for _ in 0..len {
        seed ^= seed << 13;
        seed ^= seed >> 7;
        seed ^= seed << 17;
        let idx = (seed % charset.len() as u64) as usize;
        buf.push(charset.as_bytes()[idx] as char);
    }
    buf
}

fn copy_dir_recursive(src: &std::path::Path, dst: &std::path::Path) -> ForageResult<()> {
    std::fs::create_dir_all(dst)?;
    for entry in std::fs::read_dir(src)? {
        let entry = entry?;
        let ft = entry.file_type()?;
        let path = entry.path();
        let name = entry.file_name();
        let target = dst.join(name);
        if ft.is_dir() {
            copy_dir_recursive(&path, &target)?;
        } else if ft.is_file() {
            std::fs::copy(&path, &target)?;
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                if let Ok(meta) = std::fs::metadata(&path) {
                    let _ = std::fs::set_permissions(&target, meta.permissions());
                }
            }
        }
    }
    Ok(())
}

fn find_mariadb_client() -> ForageResult<std::path::PathBuf> {
    let bin_dir = paths::bin_dir();
    if let Ok(entries) = std::fs::read_dir(&bin_dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                for c in [path.join("bin").join("mariadb"), path.join("bin").join("mysql")] {
                    if c.exists() {
                        return Ok(c);
                    }
                }
            }
        }
    }
    if let Ok(p) = which::which("mariadb") {
        return Ok(p);
    }
    if let Ok(p) = which::which("mysql") {
        return Ok(p);
    }
    Err(ForageError::BinaryNotFound {
        name: "mariadb".into(),
        locations: "searched bin/, PATH".into(),
    })
}

fn run_sql(
    client: &std::path::Path,
    socket: &std::path::Path,
    user: &str,
    pass: &str,
    sql: &str,
) -> ForageResult<()> {
    let out = std::process::Command::new(client)
        .arg("--socket").arg(socket)
        .arg("--user").arg(user)
        .arg("--password").arg(pass)
        .arg("-e").arg(sql)
        .output()?;
    if !out.status.success() {
        return Err(ForageError::Database(format!(
            "SQL failed: {}",
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    Ok(())
}
